from pydantic import BaseModel, Field
from datetime import datetime


class StepMetrics(BaseModel):
    """Metrics for a single agent step."""
    step: int = Field(..., description="1-indexed iteration number")
    input_tokens: int = Field(..., description="Tokens sent to the LLM")
    output_tokens: int = Field(..., description="Tokens generated by the LLM")
    request_time_ms: float = Field(
        ..., description="Wall-clock time for API call"
    )
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat())
    api_url: str = Field(default="")
    model_name: str = Field(default="")
    llm_output: str = Field(default="")
    sandbox_input: str = Field(default="")
    sandbox_output: str = Field(default="")
    retries: int = Field(default=0)
